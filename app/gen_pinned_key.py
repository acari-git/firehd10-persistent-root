#!/usr/bin/env python3
"""Generate Stage4PinnedProofKey.java from an X.509 EC public key DER file.

Usage: gen_pinned_key.py <public.der> <label> <output.java>

The label is embedded verbatim in the generated header comment so a host
TEST key can never be mistaken for the device key pinned during a genesis
session. The generator refuses input that is not plausibly an EC P-256
X.509 encoding.
"""

from __future__ import annotations

import base64
import sys
from pathlib import Path

HEADER = """package io.github.voidnullvalue.snusnuroot.persistence;

import java.security.KeyFactory;
import java.security.PublicKey;
import java.security.spec.X509EncodedKeySpec;
import java.util.Base64;

/**
 * GENERATED by gen_pinned_key.py - do not edit by hand.
 * Pinned proof-signer public key: LABEL
 *
 * The matching private key is the device signer's custody item and is
 * never present in this repository or in the APK (design doc section 2).
 */
public final class Stage4PinnedProofKey {
    private static final String PUBLIC_KEY_DER_B64 =
"""

FOOTER = """;

    private Stage4PinnedProofKey() {}

    /** Decodes the pinned key; throws on any corruption (callers deny). */
    public static PublicKey publicKey() {
        try {
            byte[] der = Base64.getDecoder().decode(PUBLIC_KEY_DER_B64);
            return KeyFactory.getInstance("EC")
                    .generatePublic(new X509EncodedKeySpec(der));
        } catch (Exception error) {
            throw new IllegalStateException("pinned proof key unavailable",
                    error);
        }
    }
}
"""


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    der_path, label, out_path = sys.argv[1], sys.argv[2], Path(sys.argv[3])
    der = Path(der_path).read_bytes()
    if not (80 <= len(der) <= 120) or der[0] != 0x30:
        print(f"refusing implausible EC X.509 DER ({len(der)} bytes)",
              file=sys.stderr)
        return 1
    b64 = base64.b64encode(der).decode("ascii")
    chunks = [b64[i:i + 64] for i in range(0, len(b64), 64)]
    literal = "\n            + ".join(f'"{chunk}"' for chunk in chunks)
    source = (HEADER.replace("LABEL", label)
              + "            " + literal + FOOTER)
    out_path.write_text(source, encoding="utf-8")
    print(f"wrote {out_path} from {der_path} ({len(der)} bytes, {label})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
